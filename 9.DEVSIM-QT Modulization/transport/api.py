"""Stable boundary between quantum transport and the SCF framework.

Backends receive a device-independent context and return common observables.
Optional backend diagnostics live in ``TransportResult.optional``.
"""
from typing import Any, Protocol, runtime_checkable
from transport.results import TransportResult


@runtime_checkable
class QuantumTransportBackend(Protocol):
    name: str

    def prepare(self, context: Any) -> None: ...
    def calibrate_contacts(self, context: Any) -> tuple[float, dict[str, Any]]: ...
    def solve(self, potential: Any, bias: float, context: Any) -> TransportResult: ...
    def convergence_metrics(self, previous: TransportResult | None,
                            current: TransportResult) -> dict[str, float]: ...
    def initial_convergence_metrics(self) -> dict[str, Any]: ...
    def current_relative_change(self, previous: TransportResult,
                                current: TransportResult) -> float: ...
    def validate(self, result: TransportResult) -> None: ...
    def state_stability(self, previous: TransportResult, current: TransportResult) -> tuple[bool, Any]: ...
    def converged(self, iteration: int, metrics: dict[str, Any], phi_residual: float,
                  density_residual: float, mu_change: float) -> bool: ...
    def finalize(self, result: TransportResult, bias: float, grid: Any,
                 accepted: bool) -> dict[str, Any]: ...
    def export_fields(self, result: TransportResult) -> dict[str, Any]: ...
    def result_metadata(self) -> dict[str, Any]: ...

